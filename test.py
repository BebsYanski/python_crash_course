def countResponseTimeRegressions(responseTimes):
    # Write your code here
    count = 0
    for idx,val in enumerate(responseTimes):
        if idx == 0:
            continue
        average = sum(responseTimes[:idx+1])/len(responseTimes[:idx+1])
        if val > average:
            count+=1
    return count

